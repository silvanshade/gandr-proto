    /// (add-S): ⟨Succ(m) | add(n; α)⟩ ~> ⟨m | add(n; Succ⁻(α))⟩.
    fn add_s() -> Cell
    {
        let lhs = CmdPat::cut(
            Polarity::Positive,
            ProdPat::ctor("Succ", [ProdPat::meta("m")]),
            ConsPat::op("add", [ProdPat::meta("n")], ConsPat::meta("alpha")),
        );
        let rhs = CmdPat::cut(
            Polarity::Positive,
            ProdPat::meta("m"),
            ConsPat::op(
                "add",
                [ProdPat::meta("n")],
                ConsPat::frame("Succ", ConsPat::meta("alpha")),
            ),
        );
        Cell::new(
            lhs,
            rhs,
            Orientation::PolarityDerived,
            CellProvenance::SurfaceRule,
        )
    }

    #[test]
    fn a_two_step_leg_and_a_one_step_leg_have_different_flows()
    {
        // The fused-certificate gap, at the sequent alphabet: the two-step leg
        // has two vertices and the fused leg one, so no re-indexing can make
        // the label lists agree. The full statement — that the two are
        // replay-equivalent while being flow-distinct — is the integration
        // suite's, which has an alphabet with more than one address.
        use gandr_theory_coherent_resolutions::overlap::OverlapKind;
        use gandr_theory_coherent_resolutions::overlap::enumerate_overlaps;
        use gandr_theory_coherent_resolutions::tracelet::derive_fused;

        let mut store = CellStore::new();
        let frame = store.insert(frame_defining_cell(&Sym::new("Succ")));
        let add = store.insert(add_s());
        let composition = enumerate_overlaps(&store)
            .into_iter()
            .find(|overlap| {
                overlap.kind == OverlapKind::Composition
                    && overlap.left == frame
                    && overlap.right == add
            })
            .expect("the composition overlap exists");
        let (_fused, tracelet) =
            derive_fused(&composition, &mut store).expect("the fused cell derives");
        let projected = tracelet_flow(&tracelet, &store).expect("both legs project");
        assert_eq!(2, projected.path_a.labels.len(), "the two-step leg");
        assert_eq!(1, projected.path_b.labels.len(), "the single fused step");
        assert!(
            !bool::from(legs_flow_equal(&tracelet, &store).expect("both legs project")),
            "one boundary, two flows: the projection is strictly finer than the boundary"
        );
    }
