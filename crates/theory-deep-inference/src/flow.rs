/// One end of an atom-occurrence thread — a vertex of the flow, or one of the
/// two special vertices.
///
/// The variant order is the comparison order the canonical form sorts on, and
/// it is chosen to read top-down: the premiss boundary, then the body, then the
/// conclusion boundary.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub enum FlowEnd
{
    /// The special vertex that creates every atom occurrence of the peak,
    /// carrying which occurrence of the peak this thread starts at.
    Peak
    {
        /// The occurrence's index in the peak's enumerated addresses.
        occurrence: PeakOccurrenceIndex,
    },
    /// A cell-application event, at one of its upper or lower ports.
    Vertex
    {
        /// Which event.
        vertex: FlowVertexIndex,
        /// Which incidence of that event, in the term's address order.
        port: FlowPortIndex,
    },
    /// The special vertex that destroys every atom occurrence surviving to the
    /// end of the leg.
    Join,
}

/// One **atom-occurrence thread** — an edge of the flow, with the source's
/// `up` and `lo` maps read off it.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct FlowThread
{
    /// Where the occurrence is created.
    pub up: FlowEnd,
    /// Where the occurrence is destroyed.
    pub lo: FlowEnd,
}

/// The **atom-occurrence flow** of one recorded leg.
///
/// Carries no alphabet parameter, which is the projection's whole content: once
/// the formula-level arrangement is discarded there is nothing alphabet-shaped
/// left in it.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Flow
{
    /// `η` — one content address per cell-application event, indexed by
    /// [`FlowEnd::Vertex`]'s `vertex` field.
    pub labels: Vec<CellAddress>,
    /// `E` with its `up` and `lo` maps.
    pub threads: Vec<FlowThread>,
    /// The warrant the projection's soundness fence was discharged under,
    /// carried rather than recomputed.
    pub convexity: ConvexityDischarge,
}

/// The flow of a **certificate** — its boundary, and its two legs' flows.
///
/// The boundary is carried for the same reason
/// [`crate::normal_form::TraceletNf`] carries its own: a certificate is a
/// boundary together with derivations of it, so a datum standing for one
/// without its endpoints stands for less than a certificate. A [`Flow`]
/// forgets the **formula-level arrangement**, which is the projection's whole
/// content; forgetting the arrangement is not forgetting the endpoints, and a
/// certificate-level relation that dropped them would identify two
/// certificates that transform different things the same way.
///
/// The alphabet parameter sits **here** and not on [`Flow`]. That placement is
/// the point: the combinatorial datum stays alphabet-free, and only the
/// boundary it is a flow *of* is alphabet-shaped.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct TraceletFlow<A: CellAlphabet = SequentAlphabet>
{
    /// The term both legs are derivations from, as recorded (schematic; the
    /// projection skolemizes it).
    pub peak: A::Cmd,
    /// The term both legs reach, as recorded (schematic).
    pub joins_at: A::Cmd,
    /// The first leg's flow.
    pub path_a: Flow,
    /// The second leg's flow.
    pub path_b: Flow,
}

/// Why a recorded leg could not be projected to a flow.
///
/// Refusal is data, never a panic and never a silent identity: a recorded step
/// list that is not a derivation of the peak has no flow.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum FlowObstruction<A: CellAlphabet = SequentAlphabet>
{
    /// A recorded step names a cell the store does not hold.
    UnknownCell
    {
        /// The identifier that resolved to nothing.
        cell: CellId,
    },
    /// A recorded step does not fire at its recorded position, so the leg is
    /// not a derivation and there is nothing to project.
    StepDoesNotFire
    {
        /// The step that failed to fire.
        step: Box<CellApp<A>>,
    },
    /// Every recorded step fired, and the leg landed somewhere other than the
    /// certificate's recorded join — so the leg is a derivation, but not a
    /// derivation of **this** boundary.
    ///
    /// Only [`tracelet_flow`] raises it, because only a certificate has a join
    /// to miss; [`project_flow`] is given a peak and a path and has nothing to
    /// compare against.
    LegMissesTheJoin
    {
        /// The skolemized term the leg actually reached.
        reached: Box<A::Cmd>,
    },
}

/// An atom occurrence still alive at some point in the walk.
#[derive(Clone, Debug)]
struct LiveAtom<A: CellAlphabet>
{
    /// Where the occurrence was created.
    birth: FlowEnd,
    /// The address it currently sits at.
    at: A::Pos,
}

impl Flow
{
    /// The **canonical form** — the same flow with its vertices re-indexed by a
    /// key that does not depend on the order the leg recorded them in.
    ///
    /// The key is the causal depth, then the label, then the sorted peak
    /// occurrences the vertex consumes, then its two incidence counts. Two
    /// vertices sharing a key cannot be told apart by it, and the flow is
    /// **refused** a canonical form rather than given an arbitrary one.
    ///
    /// # Contract
    /// - ensures: `Some(flow)` whose `labels` are the input's re-indexed by the
    ///   key order and whose `threads` are the input's rewritten to the new
    ///   indices and sorted; the convexity discharge is carried through
    ///   unchanged.
    /// - ensures: two flows that differ only by the order their legs recorded
    ///   independent events in have equal canonical forms.
    /// - provides: the comparison normal form [`flows_equal`] decides on.
    /// - fails: `None` when two vertices share a key, so no canonical order is
    ///   determined. Refusing is the conservative direction: an identification
    ///   not made is always sound.
    /// - panics: none.
    /// - intension: one forward pass for the depths — the recorded order is
    ///   already topological, because an occurrence is created before it is
    ///   consumed — then one stable sort of the vertices and one of the
    ///   threads.
    ///
    /// # Adequacy
    /// - hypothesis: L2 — the two outcomes own separate decision surfaces,
    ///   separated by the permutation tile (whose two legs record the same two
    ///   events in opposite orders and must canonicalize together) and by a
    ///   flow whose two vertices carry one label, one depth, and no peak
    ///   incidence, which must be refused rather than ordered.
    /// - witness: `flow::tests::the_two_legs_of_a_permutation_tile_have_one_flow`
    /// - witness: `flow::tests::indistinguishable_vertices_are_refused_a_canonical_order`
    #[inline]
    #[must_use]
    pub fn canonical(&self) -> Option<Self>
    {
        let depths = self.causal_depths();
        let mut keys: Vec<(VertexKey, FlowVertexIndex)> = Vec::with_capacity(self.labels.len());
        for (index, label) in self.labels.iter().enumerate() {
            let vertex = FlowVertexIndex::from(index);
            let depth = depths.get(index).copied().unwrap_or_default();
            keys.push((self.vertex_key(vertex, *label, depth), vertex));
        }
        keys.sort_by(|left, right| left.0.cmp(&right.0));
        if keys
            .iter()
            .zip(keys.iter().skip(1_usize))
            .any(|(left, right)| left.0 == right.0)
        {
            return None;
        }
        // `rank[old] = new`, built by walking the sorted keys.
        let mut rank: Vec<FlowVertexIndex> = alloc::vec![FlowVertexIndex::default(); keys.len()];
        let mut labels = Vec::with_capacity(keys.len());
        for (fresh, entry) in keys.iter().enumerate() {
            let old = usize::from(entry.1);
            if let Some(slot) = rank.get_mut(old) {
                *slot = FlowVertexIndex::from(fresh);
            }
            labels.push(self.labels.get(old).copied().unwrap_or(entry.0.label));
        }
        let mut threads: Vec<FlowThread> = self
            .threads
            .iter()
            .map(|thread| FlowThread {
                up: reindex_end(thread.up, &rank),
                lo: reindex_end(thread.lo, &rank),
            })
            .collect();
        threads.sort_unstable();
        Some(Self {
            labels,
            threads,
            convexity: self.convexity,
        })
    }

    /// The causal layering — each vertex's depth in the dependence order the
    /// threads induce.
    ///
    /// # Contract
    /// - requires: every `Vertex` end's index is in range for `labels`, which
    ///   [`project_flow`] establishes.
    /// - ensures: one entry per vertex; zero for a vertex consuming no
    ///   occurrence any other vertex created, and otherwise one more than the
    ///   greatest depth among those creators.
    /// - panics: none.
    #[inline]
    fn causal_depths(&self) -> Vec<CausalLayer>
    {
        let mut depths: Vec<CausalLayer> = alloc::vec![CausalLayer::default(); self.labels.len()];
        // The recorded order is topological: a thread runs from the event that
        // created an occurrence to the event that consumed it, and creation
        // precedes consumption in the leg.
        for thread in &self.threads {
            let (FlowEnd::Vertex { vertex: up, .. }, FlowEnd::Vertex { vertex: lo, .. }) =
                (thread.up, thread.lo)
            else {
                continue;
            };
            let source = depths.get(usize::from(up)).copied().unwrap_or_default();
            let lifted = CausalLayer::from(usize::from(source).saturating_add(1_usize));
            if let Some(slot) = depths.get_mut(usize::from(lo))
                && *slot < lifted
            {
                *slot = lifted;
            }
        }
        depths
    }

    /// The sort key of one vertex.
    ///
    /// # Contract
    /// - ensures: a key built only from data invariant under re-ordering
    ///   independent events — the depth, the label, the peak occurrences
    ///   consumed, and the two incidence counts.
    /// - panics: none.
    #[inline]
    fn vertex_key(
        &self,
        vertex: FlowVertexIndex,
        label: CellAddress,
        depth: CausalLayer,
    ) -> VertexKey
    {
        let mut from_peak: Vec<PeakOccurrenceIndex> = Vec::new();
        let mut upper = IncidenceCount::default();
        let mut lower = IncidenceCount::default();
        for thread in &self.threads {
            if matches!(thread.lo, FlowEnd::Vertex { vertex: at, .. } if at == vertex) {
                upper = IncidenceCount::from(usize::from(upper).saturating_add(1_usize));
                if let FlowEnd::Peak { occurrence } = thread.up {
                    from_peak.push(occurrence);
                }
            }
            if matches!(thread.up, FlowEnd::Vertex { vertex: at, .. } if at == vertex) {
                lower = IncidenceCount::from(usize::from(lower).saturating_add(1_usize));
            }
        }
        from_peak.sort_unstable();
        VertexKey {
            depth,
            label,
            from_peak,
            upper,
            lower,
        }
    }
}

/// The layer a cell-application event sits in, in the dependence order its
/// atom-occurrence threads induce.
#[repr(transparent)]
#[derive(Clone, Copy, Debug, Default, Eq, Hash, Ord, PartialEq, PartialOrd)]
struct CausalLayer(usize);

impl From<usize> for CausalLayer
{
    #[inline]
    fn from(value: usize) -> Self
    {
        Self(value)
    }
}

impl From<CausalLayer> for usize
{
    #[inline]
    fn from(value: CausalLayer) -> Self
    {
        value.0
    }
}

/// The number of upper or lower incidences one flow vertex carries.
#[repr(transparent)]
#[derive(Clone, Copy, Debug, Default, Eq, Hash, Ord, PartialEq, PartialOrd)]
struct IncidenceCount(usize);

impl From<usize> for IncidenceCount
{
    #[inline]
    fn from(value: usize) -> Self
    {
        Self(value)
    }
}

impl From<IncidenceCount> for usize
{
    #[inline]
    fn from(value: IncidenceCount) -> Self
    {
        value.0
    }
}

/// The re-indexing key of one flow vertex.
#[derive(Clone, Debug, Eq, Ord, PartialEq, PartialOrd)]
struct VertexKey
{
    /// The causal layer, compared first.
    depth: CausalLayer,
    /// The cell content address.
    label: CellAddress,
    /// The peak occurrences this vertex consumes, sorted.
    from_peak: Vec<PeakOccurrenceIndex>,
    /// How many occurrences it consumes.
    upper: IncidenceCount,
    /// How many it creates.
    lower: IncidenceCount,
}

/// Rewrite one thread end through a vertex re-indexing.
///
/// # Contract
/// - ensures: `Peak` and `Join` ends unchanged; a `Vertex` end re-indexed
///   through `rank`, or left alone when the index is out of range, which
///   [`project_flow`]'s output never produces.
/// - panics: none.
#[inline]
fn reindex_end(
    end: FlowEnd,
    rank: &[FlowVertexIndex],
) -> FlowEnd
{
    match end {
        | FlowEnd::Vertex { vertex, port } => {
            let Some(fresh) = rank.get(usize::from(vertex))
            else {
                return end;
            };
            FlowEnd::Vertex {
                vertex: *fresh,
                port,
            }
        },
        | other => other,
    }
}

/// The index of `at` among `positions`.
///
/// # Contract
/// - requires: `positions` is a term's complete address enumeration, so an
///   address of that term is present exactly once.
/// - ensures: `Some(index)` at the address's place in the enumeration, `None`
///   for an address the term does not carry.
/// - panics: none.
#[inline]
fn address_index<A>(
    positions: &[A::Pos],
    at: &A::Pos,
) -> Option<FlowPortIndex>
where
    A: CellAlphabet,
{
    let found = positions.iter().position(|candidate| candidate == at)?;
    Some(FlowPortIndex::from(found))
}

/// Whether one address lies inside a step's match image.
#[repr(transparent)]
#[derive(Clone, Copy, Debug, Default, Eq, Hash, Ord, PartialEq, PartialOrd)]
struct ImageCoverage(bool);

impl From<bool> for ImageCoverage
{
    #[inline]
    fn from(value: bool) -> Self
    {
        Self(value)
    }
}

impl From<ImageCoverage> for bool
{
    #[inline]
    fn from(value: ImageCoverage) -> Self
    {
        value.0
    }
}

/// Whether `at` covers `position` — the match image test.
///
/// # Contract
/// - ensures: positive for the redex root and every address it encloses,
///   negative for an ancestor and for an incomparable address.
/// - panics: none.
#[inline]
fn covered_by<A>(
    at: &A::Pos,
    position: &A::Pos,
) -> ImageCoverage
where
    A: CellAlphabet,
{
    ImageCoverage::from(matches!(
        A::position_order(at, position),
        PositionOrder::Same | PositionOrder::Encloses
    ))
}

/// **Project** a recorded leg to its atom-occurrence flow, or refuse it.
///
/// The peak is skolemized first, under the same discipline replay uses
/// ([`CellAlphabet::skolemize`]), so the projection is taken over the ground
/// derivation rather than the schematic one. Each recorded step is then **run**
/// rather than reasoned about: a step that does not fire has no transition to
/// attach a vertex to, and the leg is refused.
///
/// # Contract
/// - requires: `path` is the leg recorded from `peak` against `store` — the
///   same pair [`Tracelet::replay`] would be given one half of.
/// - ensures: `Ok(flow)` whose `labels` are the firing cells' position-free
///   content addresses in recorded order; whose `threads` carry one edge per
///   atom occurrence, running from the peak or from the event that created it
///   to the event that consumed it or to the conclusion; and which carries the
///   alphabet's convexity discharge for `store`.
/// - ensures: every occurrence the step's match image covers is consumed, every
///   occurrence the image covers afterwards is created, and every occurrence
///   outside the image threads through at an unchanged address — the strict
///   projection the module documents.
/// - provides: the alphabet-independent combinatorial datum flow equality is
///   decided on.
/// - fails: [`FlowObstruction`] — an unresolvable cell identifier, or a step
///   that does not fire at its recorded position.
/// - panics: none.
/// - intension: one rewrite per recorded step and two address enumerations per
///   step. A vertex's ports are numbered **inside its match image**, so one
///   step's port numbering never depends on what another step did elsewhere in
///   the term; `⊤`'s edges come out in the peak's enumeration order and `⊥`'s
///   in the conclusion's, which is the source's own boundary ordering.
///
/// # Errors
/// See the `- fails:` clause above.
///
/// # Adequacy
/// - hypothesis: L2 — the projection's three occurrence classes own separate
///   decision surfaces, separated by a leg whose single step consumes the whole
///   term (every thread runs peak-to-vertex and vertex-to-join), by a leg whose
///   two steps fire at incomparable positions (each thread touches exactly one
///   vertex, and the untouched sibling threads peak-to-join), and by a leg
///   whose second step consumes what the first created (one thread runs
///   vertex-to-vertex); the two refusals are separated by an unstored
///   identifier and a non-firing step.
/// - witness: `flow::tests::a_single_step_leg_threads_the_whole_term_through_one_vertex`
/// - witness: `flow::tests::disjoint_steps_share_no_thread`
/// - witness: `flow::tests::a_consumed_creation_is_one_thread_between_two_vertices`
/// - witness: `flow::tests::a_leg_that_does_not_fire_has_no_flow`
///
/// [`CellAlphabet::skolemize`]: gandr_theory_cell_complexes::alphabet::CellAlphabet::skolemize
/// [`Tracelet::replay`]: gandr_theory_coherent_resolutions::tracelet::Tracelet::replay
#[inline]
pub fn project_flow<A>(
    store: &CellStore<A>,
    peak: &A::Cmd,
    path: &[CellApp<A>],
) -> Result<Flow, FlowObstruction<A>>
where
    A: CellAlphabet,
{
    project_walk(store, peak, path).map(|(flow, _reached)| flow)
}

/// [`project_flow`], keeping the term the leg reached.
///
/// The reached term is what [`tracelet_flow`] checks the recorded join
/// against; [`project_flow`] itself has nothing to compare it with and drops
/// it.
///
/// # Contract
/// - ensures: [`project_flow`]'s flow, paired with the skolemized term the last
///   recorded step produced (the skolemized peak, for an empty path).
/// - panics: none.
#[inline]
fn project_walk<A>(
    store: &CellStore<A>,
    peak: &A::Cmd,
    path: &[CellApp<A>],
) -> Result<(Flow, A::Cmd), FlowObstruction<A>>
where
    A: CellAlphabet,
{
    let mut current = A::skolemize(peak);
    let mut live: Vec<LiveAtom<A>> = A::command_positions(&current)
        .into_iter()
        .enumerate()
        .map(|(index, at)| LiveAtom {
            birth: FlowEnd::Peak {
                occurrence: PeakOccurrenceIndex::from(index),
            },
            at,
        })
        .collect();
    let mut labels: Vec<CellAddress> = Vec::with_capacity(path.len());
    let mut threads: Vec<FlowThread> = Vec::new();
    for (index, step) in path.iter().enumerate() {
        let Some(cell) = store.get(step.cell)
        else {
            return Err(FlowObstruction::UnknownCell { cell: step.cell });
        };
        let Some(next) = rewrite_at(cell, &current, &step.at)
        else {
            return Err(FlowObstruction::StepDoesNotFire {
                step: Box::new(step.clone()),
            });
        };
        let vertex = FlowVertexIndex::from(index);
        labels.push(cell_address(cell));
        // Ports are numbered inside the match image, never across the whole
        // term: a vertex's incidences are its own, as the source's are the
        // rule instance's, and a global numbering would make one step's ports
        // depend on what another step did elsewhere in the term.
        let before_covered: Vec<A::Pos> = A::command_positions(&current)
            .into_iter()
            .filter(|position| bool::from(covered_by::<A>(&step.at, position)))
            .collect();
        let after_covered: Vec<A::Pos> = A::command_positions(&next)
            .into_iter()
            .filter(|position| bool::from(covered_by::<A>(&step.at, position)))
            .collect();
        // Upper edges: everything the match image covers is consumed.
        let mut surviving: Vec<LiveAtom<A>> = Vec::with_capacity(live.len());
        for atom in live {
            if !bool::from(covered_by::<A>(&step.at, &atom.at)) {
                surviving.push(atom);
                continue;
            }
            let port = address_index::<A>(&before_covered, &atom.at).unwrap_or_default();
            threads.push(FlowThread {
                up: atom.birth,
                lo: FlowEnd::Vertex { vertex, port },
            });
        }
        live = surviving;
        // Lower edges: everything the image covers afterwards is created.
        for (port, at) in after_covered.into_iter().enumerate() {
            live.push(LiveAtom {
                birth: FlowEnd::Vertex {
                    vertex,
                    port: FlowPortIndex::from(port),
                },
                at,
            });
        }
        current = next;
    }
    // The conclusion's own enumeration orders `⊥`'s edges, as the source's does.
    let final_positions = A::command_positions(&current);
    live.sort_by_key(|atom| address_index::<A>(&final_positions, &atom.at).unwrap_or_default());
    for atom in live {
        threads.push(FlowThread {
            up: atom.birth,
            lo: FlowEnd::Join,
        });
    }
    Ok((
        Flow {
            labels,
            threads,
            convexity: A::convexity_discharge(store),
        },
        current,
    ))
}

/// Whether two flows are **the same flow**.
///
/// # Contract
/// - requires: both flows were projected by [`project_flow`], so their vertex
///   indices are in range and their boundaries are anchored in the same
///   vocabulary.
/// - ensures: positive iff both flows admit a canonical form, the two canonical
///   forms are equal, and both were taken under the same convexity discharge.
/// - provides: the identification the projection licenses.
/// - panics: none.
/// - intension: **the positive answer is the load-bearing one.** A flow with no
///   canonical order answers negatively rather than refusing, because an
///   identification not made is always sound and one made wrongly is not; a
///   negative therefore means "not identified here", never "distinct".
///
/// # Adequacy
/// - hypothesis: L2 — the positive and negative surfaces are separated by the
///   permutation tile, whose two legs record the same events in opposite orders
///   and are identified, and by the fused certificate, whose two legs carry
///   different label multisets and are not.
/// - witness: `flow::tests::the_two_legs_of_a_permutation_tile_have_one_flow`
/// - witness: `flow::tests::flow_equality_is_strictly_finer_than_replay_equivalence`
#[inline]
#[must_use]
pub fn flows_equal(
    left: &Flow,
    right: &Flow,
) -> FlowEquality
{
    if left.convexity != right.convexity {
        return FlowEquality::from(false);
    }
    let (Some(left), Some(right)) = (left.canonical(), right.canonical())
    else {
        return FlowEquality::from(false);
    };
    FlowEquality::from(left == right)
}

/// Project a **certificate** to its boundary and its two legs' flows.
///
/// Both legs are projected from the shared peak and each is required to reach
/// the recorded join, so a [`TraceletFlow`] exists only for a certificate that
/// **replays**. That requirement is what makes the certificate-level relation
/// below a subrelation of
/// [`gandr_theory_coherent_resolutions::tracelet::replay_equivalent`] rather
/// than merely comparable with it: replay-equivalence is equal peaks, equal
/// joins, and two successful replays, and projecting establishes the last of
/// the three while the datum carries the first two.
///
/// # Contract
/// - requires: the tracelet's paths are the legs recorded from its peak against
///   `store`.
/// - ensures: `Ok(flow)` carrying the certificate's recorded peak and join and
///   each leg's flow, and only when **both** legs fire step by step from the
///   skolemized peak and reach the skolemized join — that is, exactly when
///   [`gandr_theory_coherent_resolutions::tracelet::Tracelet::replay`] holds.
/// - provides: the certificate-level datum [`tracelets_flow_equal`] compares.
/// - fails: [`FlowObstruction`], from whichever leg is refused first —
///   including [`FlowObstruction::LegMissesTheJoin`] for a leg that fires
///   throughout and lands elsewhere.
/// - panics: none.
///
/// # Errors
/// See the `- fails:` clause above.
///
/// # Adequacy
/// - hypothesis: L2 — the reached-the-join requirement owns its own decision
///   surface, separated by a certificate that replays and one whose second leg
///   fires completely and lands short of the recorded join.
/// - witness: `flow::tests::a_certificate_has_its_own_flow`
/// - witness: `flow::tests::a_leg_that_lands_off_the_join_has_no_certificate_flow`
#[inline]
pub fn tracelet_flow<A>(
    tracelet: &Tracelet<A>,
    store: &CellStore<A>,
) -> Result<TraceletFlow<A>, FlowObstruction<A>>
where
    A: CellAlphabet,
{
    let target = A::skolemize(&tracelet.joins_at);
    let path_a = project_leg(store, &tracelet.overlap.peak, &target, &tracelet.path_a)?;
    let path_b = project_leg(store, &tracelet.overlap.peak, &target, &tracelet.path_b)?;
    Ok(TraceletFlow {
        peak: tracelet.overlap.peak.clone(),
        joins_at: tracelet.joins_at.clone(),
        path_a,
        path_b,
    })
}

/// Project one leg of a certificate, refusing it unless it reaches `target`.
///
/// # Contract
/// - requires: `target` is the skolemized recorded join.
/// - ensures: [`project_flow`]'s flow when the leg reaches `target`.
/// - fails: [`FlowObstruction::LegMissesTheJoin`] when it fires throughout and
///   lands elsewhere, or whatever [`project_flow`] refuses it for.
/// - panics: none.
#[inline]
fn project_leg<A>(
    store: &CellStore<A>,
    peak: &A::Cmd,
    target: &A::Cmd,
    path: &[CellApp<A>],
) -> Result<Flow, FlowObstruction<A>>
where
    A: CellAlphabet,
{
    let (flow, reached) = project_walk(store, peak, path)?;
    if reached == *target {
        return Ok(flow);
    }
    Err(FlowObstruction::LegMissesTheJoin {
        reached: Box::new(reached),
    })
}

/// Whether a tracelet's **two legs have one flow** — the tile-internal reading.
///
/// This is the reading that pays: on the permutation-tile class it decides the
/// shift identification, which
/// [`crate::shift::derive_shift_equivalence`] currently confirms by running
/// both sequentializations and comparing the terms they reach.
///
/// # Contract
/// - requires: the tracelet's paths are the legs recorded from its peak.
/// - ensures: positive iff both legs project and their flows are equal.
/// - provides: a syntactic witness for the shift quotient, in place of a
///   two-order replay.
/// - fails: [`FlowObstruction`] when either leg is not a derivation of the
///   peak.
/// - panics: none.
///
/// # Errors
/// See the `- fails:` clause above.
///
/// # Adequacy
/// - hypothesis: L1 evidence — the decision surface is one flow comparison,
///   separated by the permutation tile (equal) and by the fused certificate
///   (unequal, over a boundary that replays).
/// - witness: `flow::tests::the_two_legs_of_a_permutation_tile_have_one_flow`
/// - witness: `flow::tests::flow_equality_is_strictly_finer_than_replay_equivalence`
#[inline]
pub fn legs_flow_equal<A>(
    tracelet: &Tracelet<A>,
    store: &CellStore<A>,
) -> Result<FlowEquality, FlowObstruction<A>>
where
    A: CellAlphabet,
{
    let projected = tracelet_flow(tracelet, store)?;
    Ok(flows_equal(&projected.path_a, &projected.path_b))
}

/// Whether two tracelets are **the same certificate under the projection** —
/// the certificate-to-certificate reading: one boundary, and one flow per leg.
///
/// **The boundary is part of the comparison, and leaving it out was a
/// relation-soundness defect this function once had.** Comparing flows alone
/// answers positively for two certificates that transform *different* peaks
/// into *different* joins by the same combinatorial pattern — a single
/// metavariable-carrying cell fired on two unrelated ground instances is
/// enough over the sequent alphabet — so a flow-only relation is not contained
/// in [`gandr_theory_coherent_resolutions::tracelet::replay_equivalent`] and
/// the strict nesting the module claims is false for it. Forgetting the
/// formula-level **arrangement**, which is what the projection is for, is not
/// the same as forgetting the **endpoints**.
///
/// # Contract
/// - requires: both tracelets' paths are the legs recorded from their own
///   peaks, and both are read against `store`.
/// - ensures: positive iff both certificates project — which forces equal
///   recorded boundaries to be reached, so both replay — **and** their peaks
///   agree, their joins agree, and their two flows agree pairwise.
/// - ensures: a positive answer implies
///   [`gandr_theory_coherent_resolutions::tracelet::replay_equivalent`]: equal
///   peaks and equal joins are compared here, and both replays are what
///   [`tracelet_flow`] established.
/// - provides: the relation the module measures against replay-equivalence; it
///   is **strictly finer**, and a positive there does not follow from a
///   positive here.
/// - fails: [`FlowObstruction`] when either tracelet is not a pair of
///   derivations of its own recorded boundary.
/// - panics: none.
/// - intension: **the positive answer is the load-bearing one**, as at
///   [`flows_equal`]: a negative means "not identified here", never "distinct".
///
/// # Errors
/// See the `- fails:` clause above.
///
/// # Adequacy
/// - hypothesis: L2 — the boundary conjunct and the flow conjunct own separate
///   decision surfaces, separated by a certificate against itself, by two
///   replay-equivalent certificates whose legs carry different flows, and by
///   two certificates whose flows are equal over different boundaries.
/// - witness: `flow::tests::a_certificate_has_its_own_flow`
/// - witness: `flow::tests::replay_equivalent_certificates_can_carry_different_flows`
/// - witness: `flow::tests::equal_flows_over_different_boundaries_are_not_one_certificate`
/// - witness: `flow::tests::flow_equality_implies_replay_equivalence`
#[inline]
pub fn tracelets_flow_equal<A>(
    left: &Tracelet<A>,
    right: &Tracelet<A>,
    store: &CellStore<A>,
) -> Result<FlowEquality, FlowObstruction<A>>
where
    A: CellAlphabet,
{
    let left = tracelet_flow(left, store)?;
    let right = tracelet_flow(right, store)?;
    if left.peak != right.peak || left.joins_at != right.joins_at {
        return Ok(FlowEquality::from(false));
    }
    let heads = flows_equal(&left.path_a, &right.path_a);
    let tails = flows_equal(&left.path_b, &right.path_b);
    Ok(FlowEquality::from(bool::from(heads) && bool::from(tails)))
}

