//! **The atom-occurrence flow projection** — a *prototype* certificate-side
//! identity discipline that sits **beside** replay-equivalence and the tracelet
//! normal form, and is consumed by nothing.
//!
//! # Status: prototype, and deliberately inert
//!
//! Nothing in this crate or downstream calls into this module.
//! [`gandr_theory_coherent_resolutions::tracelet::replay_equivalent`] remains
//! the identity criterion and [`crate::normal_form::nf_equal`] remains the
//! decidable fast path. This module exists to **measure** one question: whether
//! tracking cell and atom occurrences across a recorded leg — and forgetting
//! the formula-level arrangement — yields a relation that coincides with
//! certificate identity. It answers by disagreeing with both neighbours on
//! recorded fixtures, and the disagreements are the deliverable; see the
//! differential suite (`flow::tests` in the crate's integration target).
//!
//! # The construction being instantiated
//!
//! The source object is the **atomic flow** of A. Guglielmi and T. Gundersen,
//! "Normalisation control in deep inference via atomic flows", Logical Methods
//! in Computer Science 4(1:9) 2008, DOI `10.2168/LMCS-4(1:9)2008`, Definition
//! 3.2: a tuple `(V, E, η, up, lo)` where `V` is a finite vertex set, `E` a
//! finite edge set, `η` labels each vertex with the structural rule instance it
//! stands for, and `up`/`lo` map each edge to a vertex or to one of two special
//! vertices `⊤` and `⊥` — `⊤` "creates all the atom occurrences in the premiss"
//! and `⊥` "destroys all atom occurrences in the conclusion". Edges are atom
//! occurrences; the logical structure of the formulas is discarded; and
//! **linear rules introduce no vertices**, because they neither create nor
//! destroy atoms.
//!
//! The instantiation for gandr replaces two components and keeps the rest:
//!
//! - `V` is the **cell-application events** of one recorded leg, in place of
//!   the six structural rule instances of the source system.
//! - `η` labels a vertex with the firing cell's **position-free content
//!   address** ([`cell_address`]), in place of the six rule labels. The
//!   position is deliberately absent: [`crate::normal_form::prim_address`]
//!   digests the position as well as the content, and a flow that labelled its
//!   vertices with primitive addresses would re-import exactly the arrangement
//!   the projection is defined to forget.
//! - `E`, `up`, `lo`, `⊤` and `⊥` are the source's, verbatim: an edge is one
//!   atom occurrence's thread, `⊤` creates the peak's occurrences, and `⊥`
//!   destroys the occurrences surviving to the leg's end.
//!
//! **The load-bearing consequence is that [`Flow`] carries no alphabet
//! parameter.** Once the arrangement is discarded there is nothing
//! alphabet-shaped left: a flow is combinatorial data, and only
//! [`project_flow`] is generic. That is the shape the source's Definition 3.2
//! has and the shape the recorded certificate data does not, and it is the
//! sharpest available evidence that the projection is the right object rather
//! than a re-encoding of what was already there.
//!
//! **The source is this one and not the BV reading, and the difference is
//! structural rather than a matter of preference.** M. Acclavio, L.
//! Straßburger and V. Zamdzhiev, "Proof Identity and Categorical Models of BV",
//! FSCD 2026, DOI `10.4230/LIPIcs.FSCD.2026.22`, also defines atomic flows —
//! but for BV, whose rules are linear in atoms apart from the atomic identity
//! and atomic cut, so its flows are *generated by* the identity wire, the
//! crossing, the cup and the cap (their Definition 5) and carry no boxes at
//! all. A gandr cell consumes a whole left-hand skeleton and produces a whole
//! right-hand one, at arities the cell chooses, so its flow needs a labelled
//! vertex of arbitrary arity — which is Definition 3.2's shape and not
//! Definition 5's. The practical consequence is stated under the caveats on
//! this crate's design record: **there is nothing in a gandr flow to yank**, so
//! the BV correspondence between cut elimination and yanking has no counterpart
//! here to transfer or to fail.
//!
//! **What is imported is the projection's *shape*; the *control* theory is not
//! imported and is not claimed.** Definition 3.2 supplies the object — a
//! labelled vertex set, atom-occurrence edges, and two boundary vertices — and
//! that is the whole of what this module takes from the source. The source
//! line's normalisation control (streamlining, the splitting measures, and the
//! flow rewriting that drives them) is stated for classical deep-inference
//! systems, and the intuitionistic presentation's own cut elimination is
//! established indirectly, by simulation in sequent and hypersequent systems,
//! rather than internally. So no control result reaches gandr's setting by
//! citation, and none is used here: this module defines a relation and decides
//! it, and every soundness argument it rests on — the convexity fence above,
//! the strict projection's safety, the boundary conjunct below — is gandr's
//! own and is discharged in this tree.
//!
//! One boundary convention does diverge from the source, deliberately. The
//! source's flows forget the premiss and the conclusion outright; this
//! projection **anchors `⊤`** — a peak occurrence's thread carries which
//! occurrence of the peak it is — because the relation being measured compares
//! two legs *of one peak*, and an unanchored comparison would identify legs
//! that consume different parts of it.
//!
//! # What an atom occurrence is here, and the resolution ceiling
//!
//! An atom occurrence is an address in the alphabet's own vocabulary —
//! an entry of [`CellAlphabet::command_positions`]. The projection is
//! therefore exactly as fine as that vocabulary and no finer, which is the same
//! ceiling [`crate::footprint`] documents for the same reason: over
//! [`gandr_theory_cell_complexes::sequent::SequentAlphabet`] a command pattern
//! is one cut whose children are a producer and a consumer, so a term has
//! exactly one address and every leg over it projects to a flow whose every
//! thread runs from `⊤` to `⊥` through one vertex. The differential suite
//! therefore runs on the toy alphabet, the one alphabet in the tree whose terms
//! nest commands.
//!
//! # The strict projection, and the residual map it does not need
//!
//! What is built here is the **strict** projection: a step consumes every
//! occurrence its match image covers and creates every occurrence the image
//! covers afterwards, with occurrences outside the image threading through
//! untouched at unchanged addresses. Nothing inside a redex is traced from one
//! side of the step to the other.
//!
//! That is a real restriction and it is the one place this module stops short
//! of the definition it instantiates. The **lax** projection would additionally
//! carry a redex's hole contents across the step — the rule's own metavariable
//! at its left-hand address maps to the same metavariable at its right-hand
//! address, so the occurrences beneath it are transported rather than destroyed
//! and re-created. Computing that needs a **residual map on positions**, which
//! is precisely the debt [`crate::footprint`] names as owed and which
//! [`gandr_theory_coherent_resolutions::rewrite::CellApp`] has no room for. The
//! strict projection is sound without it — refusing to identify two occurrences
//! is always the safe direction — and it is exact on the permutation-tile
//! class, where the two images are disjoint and nothing needs transporting. It
//! is *coarser than the definition* only outside that class.
//!
//! # The soundness fence, which the projection inherits rather than escapes
//!
//! **Convexity is formula-level arrangement, so a flow cannot see it.** The
//! shift guard's third conjunct exists because disjointness of supports does
//! not imply independence once matches must be convex: applying one rule can
//! create a directed path that destroys another's convexity, on hyperedge sets
//! that never met. A flow has discarded exactly the structure that path lives
//! in. The projection is therefore sound on precisely the fence
//! [`ConvexityDischarge::LeftConnectedOverAcyclicTarget`] already names, every
//! [`Flow`] carries the discharge it was taken under, and an alphabet
//! answering [`ConvexityDischarge::ReCheckRequired`] must be refused the
//! identification rather than have the question re-derived here.
//!
//! # Where this sits between its two neighbours
//!
//! Measured on the fixtures in the differential suite, the three relations on
//! certificate data are strictly nested:
//!
//! - **Shift equivalence** (what [`crate::normal_form`] decides) is strictly
//!   inside flow equality. The shift guard refuses a pair whose *cells* overlap
//!   even at incomparable positions, because it asks
//!   [`gandr_theory_coherent_resolutions::overlap::overlaps_between`], which is
//!   a question about the alphabet. The projection reads the *instance*, where
//!   two disjoint images share no occurrence whatever the cells could have done
//!   elsewhere, so it licenses that pair.
//! - **Flow equality** is strictly inside replay-equivalence.
//!   [`gandr_theory_coherent_resolutions::tracelet::replay_equivalent`]
//!   compares a boundary and asks each side to replay, ignoring the recorded
//!   paths outright, so no relation that reads the paths can coincide with it.
//!   [`gandr_theory_coherent_resolutions::tracelet::derive_fused`] exhibits the
//!   gap in the tree: one boundary whose `path_a` is a two-step derivation and
//!   whose `path_b` is a single fused step — replay-equal by construction, and
//!   flow-distinct because the vertex label multisets differ.
//!
//! So a flow is **strictly finer than certificate identity**, and reading
//! "equal flows" as "same certificate" is wrong in the direction that does not
//! announce itself. What flow equality does decide, on the permutation-tile
//! class, is the *shift* identification — which is the quotient
//! [`crate::shift::derive_shift_equivalence`] currently pays two term rewrites
//! per pair to confirm.
//!
//! # The nesting is a claim about **certificates**, and it costs the boundary
//!
//! The second containment above is a statement about a relation on
//! certificates, and it holds only for a certificate-level relation that
//! compares certificates — boundaries included. A relation reading the two
//! projected flows and nothing else is **not** inside replay-equivalence: one
//! metavariable-carrying cell fired on two unrelated ground instances produces
//! two legs with the same flow over two different boundaries, which
//! replay-equivalence separates and a flow-only comparison does not. The
//! chain's second strictness was published in that broken form and is
//! corrected here rather than quietly narrowed;
//! `flow::tests::equal_flows_over_different_boundaries_are_not_one_certificate`
//! is the regression that fails if the boundary conjunct is dropped again.
//!
//! The remedy is the one [`crate::normal_form::TraceletNf`] already took:
//! **the certificate-level datum carries the boundary**, so
//! [`TraceletFlow`] holds a peak and a join beside the two flows and
//! [`tracelet_flow`] refuses a leg that lands anywhere else. Containment is
//! then a consequence of what the datum **is** rather than a property of how
//! it happens to be compared, and it survives any later change to the flow
//! comparison itself.
//!
//! **The no-alphabet-parameter result above survives this intact, and a reader
//! who meets a boundary here should not conclude otherwise.** [`Flow`] is
//! untouched and still carries no alphabet parameter; the parameter the
//! boundary brings sits one level up, on [`TraceletFlow`]. Forgetting the
//! formula-level arrangement is the projection's content, forgetting the
//! endpoints never was, and conflating the two is exactly what produced the
//! defect.
//!
//! # One discipline, in two places: refuse where a choice would be arbitrary
//!
//! This module declines to answer twice, for one reason, and the repetition is
//! what makes it a discipline rather than two local decisions.
//!
//! - [`Flow::canonical`] gives **no** canonical form to a flow whose vertices
//!   share a re-indexing key, rather than ordering them arbitrarily.
//! - The convexity fence gives **no** identification on a carrier answering
//!   [`ConvexityDischarge::ReCheckRequired`], rather than re-deriving the
//!   question with the structure that would settle it already discarded.
//!
//! **The rule both follow: an identification not made is always sound, and one
//! made wrongly is not.** So a negative from this layer means "not identified
//! here" and never "distinct", and a third refusal met later reads the same
//! way.
//!
//! It is also why a hazard the source line carries does not reach these
//! relations. Cycle removal in that literature is **non-confluent** — the
//! transformation has no canonical result — so an identity defined by
//! quotienting under it inherits a choice of representative. None of the
//! relations here is defined that way: each is an explicit predicate on
//! recorded data, and at the one place a representative choice would have been
//! needed, the canonical form's ties, this module declines to make one.
//!
//! # Cost
//!
//! Deliberately unoptimized: one rewrite per recorded step, plus a linear scan
//! of the term's addresses per step and a quadratic address lookup inside it.
//! It is a measurement instrument, not a fast path.
//!
//! [`CellAlphabet::command_positions`]: gandr_theory_cell_complexes::alphabet::CellAlphabet::command_positions
//! [`ConvexityDischarge::LeftConnectedOverAcyclicTarget`]: gandr_theory_cell_complexes::alphabet::ConvexityDischarge::LeftConnectedOverAcyclicTarget
//! [`ConvexityDischarge::ReCheckRequired`]: gandr_theory_cell_complexes::alphabet::ConvexityDischarge::ReCheckRequired

