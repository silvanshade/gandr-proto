//! Deterministic record-safe chunk boundary detection for future Prolly-Bao.
//!
//! # Provenance
//!
//! This crate is a storage-tier skeleton absorbed directly from the owner's
//! unpublished `mach` `prolly-bao-chunker` crate (Apache-2.0, same owner;
//! source commit `fb78601`). It is a direct source absorption adapted to the
//! gandr storage tier and lint discipline, not an external dependency. See the
//! ratified vendor plan in `docs/research/massive-term-design.md` §6.1.
//!
//! # Crate boundary
//!
//! This crate is `#![no_std]` with **zero runtime dependencies** (an empty
//! `[dependencies]` table) — a deliberate property kept visible at the crate
//! boundary so the chunker stays a minimal, self-contained substrate. Its
//! 85-byte fixed-order [`ChunkerParams::commitment_bytes`] parameter commitment
//! ([`PARAMETER_COMMITMENT_LEN`], magic `MPBCHK01`, big-endian fields) is the
//! primitive downstream layers bind so records cannot be replayed under
//! incompatible chunking parameters.
//!
//! `current`: this crate owns only boundary detection over already-canonical
//! ordered records. It does not serialize records, build Prolly-Bao trees, hash
//! nodes with BLAKE3, store blocks, produce proofs, or talk to storage and
//! transport adapters.
//!
//! `designed direction`: callers commit [`ChunkerParams::commitment_bytes`]
//! into Prolly-Bao root or proof context so the same records cannot be replayed
//! under incompatible chunking parameters.
//!
//! `open decision`: stronger adversarial boundary-grinding mitigations may add
//! new algorithm profiles later. The only supported profile here is the local,
//! deterministic, FastCDC-2020-inspired Gear scanner identified by
//! [`AlgorithmVersion::FASTCDC_2020`].

