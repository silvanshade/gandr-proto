/// Validated byte and record limits for record-safe chunking.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ChunkLimits
{
    /// Minimum bytes before hash-predicate cuts are allowed.
    min_bytes: ByteCount,
    /// Target bytes used to derive the Gear cut mask.
    target_bytes: ByteCount,
    /// Hard byte cap for a chunk.
    max_bytes: ByteCount,
    /// Minimum records before hash-predicate cuts are allowed.
    min_records: RecordCount,
    /// Target records committed for the current profile and future profiles.
    target_records: RecordCount,
    /// Hard record-count cap for a chunk.
    max_records: RecordCount,
}

impl ChunkLimits
{
    /// Creates validated chunk byte and record limits.
    ///
    /// # Errors
    ///
    /// Returns [`ChunkerError::InvalidParameters`] when any limit is zero, when
    /// byte or record limits are inverted, or when target bytes exceed the
    /// current release-build validation cap.
    #[inline]
    #[must_use = "invalid chunk limits must be handled"]
    pub const fn new(
        min_bytes: ByteCount,
        target_bytes: ByteCount,
        max_bytes: ByteCount,
        min_records: RecordCount,
        target_records: RecordCount,
        max_records: RecordCount,
    ) -> Result<Self, ChunkerError>
    {
        if min_bytes.0 == 0_u64 || target_bytes.0 == 0_u64 || max_bytes.0 == 0_u64 {
            return Err(ChunkerError::InvalidParameters {
                reason: InvalidParameterReason::ZeroByteLimit,
            });
        }

        if min_records.0 == 0_u32 || target_records.0 == 0_u32 || max_records.0 == 0_u32 {
            return Err(ChunkerError::InvalidParameters {
                reason: InvalidParameterReason::ZeroRecordLimit,
            });
        }

        if min_bytes.0 > target_bytes.0 {
            return Err(ChunkerError::InvalidParameters {
                reason: InvalidParameterReason::MinByteExceedsTargetByte,
            });
        }

        if target_bytes.0 > max_bytes.0 {
            return Err(ChunkerError::InvalidParameters {
                reason: InvalidParameterReason::InvertedByteLimits,
            });
        }

        if target_bytes.0 > MAX_TARGET_BYTES {
            return Err(ChunkerError::InvalidParameters {
                reason: InvalidParameterReason::TargetByteExceedsU32,
            });
        }

        if min_records.0 > target_records.0 || target_records.0 > max_records.0 {
            return Err(ChunkerError::InvalidParameters {
                reason: InvalidParameterReason::InvertedRecordLimits,
            });
        }

        return Ok(Self {
            min_bytes,
            target_bytes,
            max_bytes,
            min_records,
            target_records,
            max_records,
        });
    }

    /// Returns the default FastCDC-inspired limit profile.
    #[inline]
    #[must_use]
    pub const fn default_fastcdc() -> Self
    {
        return Self {
            min_bytes: ByteCount(DEFAULT_MIN_BYTES),
            target_bytes: ByteCount(DEFAULT_TARGET_BYTES),
            max_bytes: ByteCount(DEFAULT_MAX_BYTES),
            min_records: RecordCount(DEFAULT_MIN_RECORDS),
            target_records: RecordCount(DEFAULT_TARGET_RECORDS),
            max_records: RecordCount(DEFAULT_MAX_RECORDS),
        };
    }

    /// Returns the minimum byte count before hash cuts are allowed.
    #[inline]
    #[must_use]
    pub const fn min_bytes(&self) -> ByteCount
    {
        return self.min_bytes;
    }

    /// Returns the target byte count used to derive the Gear cut mask.
    #[inline]
    #[must_use]
    pub const fn target_bytes(&self) -> ByteCount
    {
        return self.target_bytes;
    }

    /// Returns the hard maximum byte count for a chunk.
    #[inline]
    #[must_use]
    pub const fn max_bytes(&self) -> ByteCount
    {
        return self.max_bytes;
    }

    /// Returns the minimum record count before hash cuts are allowed.
    #[inline]
    #[must_use]
    pub const fn min_records(&self) -> RecordCount
    {
        return self.min_records;
    }

    /// Returns the committed target record count.
    #[inline]
    #[must_use]
    pub const fn target_records(&self) -> RecordCount
    {
        return self.target_records;
    }

    /// Returns the hard maximum record count for a chunk.
    #[inline]
    #[must_use]
    pub const fn max_records(&self) -> RecordCount
    {
        return self.max_records;
    }
}

impl Default for ChunkLimits
{
    #[inline]
    fn default() -> Self
    {
        return Self::default_fastcdc();
    }
}

/// Validated chunker parameters and their stable commitment bytes.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ChunkerParams
{
    /// Committed algorithm profile.
    algorithm_version: AlgorithmVersion,
    /// Committed Gear table version.
    gear_table_version: GearTableVersion,
    /// Committed seed policy and salt bytes.
    seed_policy: SeedPolicy,
    /// Committed input normalization policy.
    normalization_policy: NormalizationPolicy,
    /// Committed record-boundary rule.
    record_boundary_rule: RecordBoundaryRule,
    /// Validated byte and record limits.
    limits: ChunkLimits,
    /// Stable fixed-order parameter commitment bytes.
    commitment: ParameterCommitment,
    /// Initial Gear state for each chunk after seed-policy mixing.
    initial_state: GearState,
    /// Gear cut mask derived from target bytes.
    cut_mask: CutMask,
}

impl ChunkerParams
{
    /// Creates validated chunker parameters.
    ///
    /// # Errors
    ///
    /// Returns a precise [`ChunkerError`] when an algorithm, table,
    /// normalization, seed, boundary rule, or limit value is unsupported or
    /// invalid.
    #[must_use = "invalid chunker parameters must be handled"]
    #[inline]
    pub fn new(
        algorithm_version: AlgorithmVersion,
        gear_table_version: GearTableVersion,
        seed_policy: SeedPolicy,
        normalization_policy: NormalizationPolicy,
        record_boundary_rule: RecordBoundaryRule,
        limits: ChunkLimits,
    ) -> Result<Self, ChunkerError>
    {
        if let SeedPolicyKind::Unsupported(kind) = seed_policy.kind {
            return Err(ChunkerError::UnsupportedSeedPolicy {
                kind: u8::from(kind),
            });
        }

        let commitment = build_parameter_commitment(
            algorithm_version,
            gear_table_version,
            &seed_policy,
            normalization_policy,
            record_boundary_rule,
            &limits,
        );
        let initial_state = derive_initial_state(&seed_policy);
        let cut_mask = cut_mask_for_target(limits.target_bytes());

        return Ok(Self {
            algorithm_version,
            gear_table_version,
            seed_policy,
            normalization_policy,
            record_boundary_rule,
            limits,
            commitment,
            initial_state,
            cut_mask,
        });
    }

    /// Returns the default supported FastCDC-inspired profile.
    #[inline]
    #[must_use]
    pub fn default_fastcdc() -> Self
    {
        let limits = ChunkLimits::default_fastcdc();
        let seed_policy = SeedPolicy::NONE;
        let commitment = build_parameter_commitment(
            AlgorithmVersion::FASTCDC_2020,
            GearTableVersion::MACH_V1,
            &seed_policy,
            NormalizationPolicy::NONE,
            RecordBoundaryRule::BETWEEN_RECORDS,
            &limits,
        );
        let initial_state = derive_initial_state(&seed_policy);
        let cut_mask = cut_mask_for_target(limits.target_bytes());

        return Self {
            algorithm_version: AlgorithmVersion::FASTCDC_2020,
            gear_table_version: GearTableVersion::MACH_V1,
            seed_policy,
            normalization_policy: NormalizationPolicy::NONE,
            record_boundary_rule: RecordBoundaryRule::BETWEEN_RECORDS,
            limits,
            commitment,
            initial_state,
            cut_mask,
        };
    }

    /// Returns the stable fixed-order parameter commitment.
    #[inline]
    #[must_use]
    pub const fn commitment_bytes(&self) -> &ParameterCommitment
    {
        return &self.commitment;
    }

    /// Returns the committed algorithm version.
    #[inline]
    #[must_use]
    pub const fn algorithm_version(&self) -> AlgorithmVersion
    {
        return self.algorithm_version;
    }

    /// Returns the committed Gear table version.
    #[inline]
    #[must_use]
    pub const fn gear_table_version(&self) -> GearTableVersion
    {
        return self.gear_table_version;
    }

    /// Returns the committed seed policy.
    #[inline]
    #[must_use]
    pub const fn seed_policy(&self) -> &SeedPolicy
    {
        return &self.seed_policy;
    }

    /// Returns the committed normalization policy.
    #[inline]
    #[must_use]
    pub const fn normalization_policy(&self) -> NormalizationPolicy
    {
        return self.normalization_policy;
    }

    /// Returns the committed record-boundary rule.
    #[inline]
    #[must_use]
    pub const fn record_boundary_rule(&self) -> RecordBoundaryRule
    {
        return self.record_boundary_rule;
    }

    /// Returns validated chunk limits.
    #[inline]
    #[must_use]
    pub const fn limits(&self) -> &ChunkLimits
    {
        return &self.limits;
    }

    /// Returns the chunk-local initial Gear state.
    const fn initial_state(&self) -> GearState
    {
        return self.initial_state;
    }

    /// Returns the Gear cut mask.
    const fn cut_mask(&self) -> CutMask
    {
        return self.cut_mask;
    }
}

