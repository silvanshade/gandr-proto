{
    #[inline]
    fn fmt(
        &self,
        f: &mut fmt::Formatter<'_>,
    ) -> fmt::Result
    {
        return match *self {
            | Self::ZeroByteLimit => write!(f, "a byte limit is zero"),
            | Self::MinByteExceedsTargetByte => {
                write!(f, "minimum byte limit must not exceed target byte limit")
            },
            | Self::InvertedByteLimits => {
                write!(f, "target byte limit must not exceed max byte limit")
            },
            | Self::ZeroRecordLimit => write!(f, "a record limit is zero"),
            | Self::InvertedRecordLimits => {
                write!(f, "record limits must satisfy min <= target <= max")
            },
            | Self::TargetByteExceedsU32 => {
                write!(f, "target byte limit exceeds u32::MAX")
            },
        };
    }
}

