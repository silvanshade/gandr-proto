pub enum ArithmeticOperation
{
    /// A byte offset or canonical byte-stream length overflowed [`u64`].
    ByteOffset,
    /// A record index overflowed [`u64`].
    RecordIndex,
    /// A record byte length could not be represented safely.
    RecordLength,
    /// A chunk byte count overflowed [`u64`].
    ChunkByteCount,
    /// A chunk record count overflowed [`u32`].
    ChunkRecordCount,
}

/// Error returned by parameter validation or record-safe boundary detection.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ChunkerError
{
    /// Parameter limits are zero or inverted.
    InvalidParameters
    {
        /// Specific invalid parameter condition.
        reason: InvalidParameterReason,
    },
    /// Checked arithmetic failed while deriving offsets or counts.
    ArithmeticOverflow
    {
        /// Operation that overflowed.
        operation: ArithmeticOperation,
    },
    /// Record byte spans were not a contiguous monotonic partition.
    NonMonotonicRecordSpans
    {
        /// Index of the offending record span.
        index: usize,
    },
    /// A record span extended beyond the canonical byte stream.
    RecordSpanOutOfBounds
    {
        /// Index of the offending record span.
        index: usize,
        /// Observed end byte offset.
        end: u64,
        /// Canonical byte stream length.
        canonical_len: u64,
    },
    /// Canonical bytes were not covered by the provided record spans.
    UncoveredCanonicalBytes
    {
        /// End offset covered by the last record span.
        covered_end: u64,
        /// Canonical byte stream length.
        canonical_len: u64,
    },
    /// A single complete record exceeded the hard chunk byte cap.
    RecordByteLengthCapViolation
    {
        /// Index of the offending record.
        record_index: u64,
        /// Record byte length.
        record_len: u64,
        /// Maximum bytes allowed in one chunk.
        max_bytes: u64,
    },
    /// Adding the next complete record would violate the byte cap before the
    /// current chunk can satisfy minimum limits.
    ChunkByteCapViolation
    {
        /// Start record of the chunk being built.
        chunk_start_record: u64,
        /// Next record that would violate the byte cap.
        next_record_index: u64,
        /// Attempted chunk byte count.
        attempted_bytes: u64,
        /// Maximum bytes allowed in one chunk.
        max_bytes: u64,
    },
    /// Adding the next complete record would violate the record cap before the
    /// current chunk can satisfy minimum limits.
    ChunkRecordCapViolation
    {
        /// Start record of the chunk being built.
        chunk_start_record: u64,
        /// Next record that would violate the record cap.
        next_record_index: u64,
        /// Attempted chunk record count.
        attempted_records: u32,
        /// Maximum records allowed in one chunk.
        max_records: u32,
    },
    /// Algorithm version is not implemented by this crate.
    UnsupportedAlgorithmVersion
    {
        /// Raw unsupported algorithm version.
        raw: u16,
    },
    /// Gear table version is not implemented by this crate.
    UnsupportedGearTableVersion
    {
        /// Raw unsupported Gear table version.
        raw: u16,
    },
    /// Normalization policy is not implemented by this crate.
    UnsupportedNormalizationPolicy
    {
        /// Raw unsupported normalization policy.
        raw: u8,
    },
    /// Seed policy is not implemented by this crate.
    UnsupportedSeedPolicy
    {
        /// Raw unsupported seed kind.
        kind: u8,
    },
    /// Record-boundary rule is not implemented by this crate.
    UnsupportedRecordBoundaryRule
    {
        /// Raw unsupported record-boundary rule.
        raw: u8,
    },
}

impl fmt::Display for ChunkerError
{
    #[inline]
    fn fmt(
        &self,
        f: &mut fmt::Formatter<'_>,
    ) -> fmt::Result
    {
        return match *self {
            | Self::InvalidParameters { reason } => {
                write!(f, "invalid chunker parameters: {reason}")
            },
            | Self::ArithmeticOverflow { operation } => {
                write!(f, "arithmetic overflow while computing {operation}")
            },
            | Self::NonMonotonicRecordSpans { index } => {
                write!(f, "record span {index} is not contiguous")
            },
            | Self::RecordSpanOutOfBounds {
                index,
                end,
                canonical_len,
            } => write!(
                f,
                "record span {index} ends at {end}, beyond canonical byte length {canonical_len}"
            ),
            | Self::UncoveredCanonicalBytes {
                covered_end,
                canonical_len,
            } => write!(
                f,
                "record spans cover bytes through {covered_end}, not canonical length {canonical_len}"
            ),
            | Self::RecordByteLengthCapViolation {
                record_index,
                record_len,
                max_bytes,
            } => write!(
                f,
                "record {record_index} length {record_len} exceeds maximum chunk bytes {max_bytes}"
            ),
            | Self::ChunkByteCapViolation {
                chunk_start_record,
                next_record_index,
                attempted_bytes,
                max_bytes,
            } => write!(
                f,
                "chunk from record {chunk_start_record} cannot add record {next_record_index} without reaching {attempted_bytes} bytes, exceeding max bytes {max_bytes}"
            ),
            | Self::ChunkRecordCapViolation {
                chunk_start_record,
                next_record_index,
                attempted_records,
                max_records,
            } => write!(
                f,
                "chunk from record {chunk_start_record} cannot add record {next_record_index} without reaching {attempted_records} records, exceeding max records {max_records}"
            ),
            | Self::UnsupportedAlgorithmVersion { raw } => {
                write!(f, "unsupported algorithm version {raw}")
            },
            | Self::UnsupportedGearTableVersion { raw } => {
                write!(f, "unsupported Gear table version {raw}")
            },
            | Self::UnsupportedNormalizationPolicy { raw } => {
                write!(f, "unsupported normalization policy {raw}")
            },
            | Self::UnsupportedSeedPolicy { kind } => {
                write!(f, "unsupported seed policy {kind}")
            },
            | Self::UnsupportedRecordBoundaryRule { raw } => {
                write!(f, "unsupported record-boundary rule {raw}")
            },
        };
    }
}

